import AxeBuilder from "@axe-core/playwright";
import { expect, test } from "@playwright/test";

test("guided no-resume intake presents real facts, requires reapproval after edits, and reflows at 320px", async ({ page }) => {
  await page.setViewportSize({ width: 320, height: 720 });
  await page.goto("/get-started");
  await page.getByLabel("Full name required").fill("Guided Customer");
  await page.getByLabel("Email address required").fill("guided@example.invalid");
  await page.getByRole("radio", { name: "Build my background without a resume" }).check();
  await expect(page.getByLabel("Resume required")).toHaveCount(0);
  await page.getByLabel("I am considering a career change.").check();
  await page.getByRole("button", { name: /Save and continue/ }).click();
  await page.getByRole("checkbox", { name: /Supporting customers/ }).first().check();
  await page.getByRole("button", { name: /Save and continue/ }).click();
  await page.getByRole("button", { name: "Add experience" }).click();
  await page.getByLabel("Employer, organization, school or project").fill("Fixture Store");
  await page.getByLabel("Your actual role or relationship").fill("Cashier");
  await expect(page.getByRole("checkbox", { name: "Handled payments" })).not.toBeChecked();
  await page.getByRole("checkbox", { name: "Handled payments" }).check();
  await page.getByLabel(/I checked for missing or outdated/).check();
  await page.getByRole("button", { name: /Save and continue/ }).click();
  await page.getByRole("checkbox", { name: "Remote" }).check();
  await page.getByLabel("U.S. state or District of Columbia required").selectOption("VA");
  await page.getByRole("checkbox", { name: "Full Time" }).check();
  await page.getByLabel(/I agree to/).check();
  await page.getByRole("button", { name: "Review my information" }).click();
  await expect(page.getByRole("heading", { name: "Confirm your saved information" })).toBeFocused();
  await expect(page.getByRole("region", { name: "Experience 1: Cashier" })).toContainText("Fixture Store");
  await expect(page.getByRole("region", { name: "Experience 1: Cashier" })).toContainText("Handled payments");
  await expect(page.getByRole("button", { name: "Confirm and submit intake" })).toBeDisabled();
  await page.getByLabel(/I reviewed the actual information/).check();
  await page.getByRole("button", { name: "Edit experience 1: cashier" }).click();
  await page.getByLabel("Employer, organization, school or project").fill("Corrected Store");
  await page.getByLabel(/I checked for missing or outdated/).check();
  await page.getByRole("button", { name: "Save and return to review" }).click();
  await expect(page.getByLabel(/I reviewed the actual information/)).toHaveCount(0);
  await page.getByRole("button", { name: "Review my information" }).click();
  await expect(page.getByRole("region", { name: "Experience 1: Cashier" })).toContainText("Corrected Store");
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= document.documentElement.clientWidth)).toBe(true);
  const accessibility = await new AxeBuilder({ page }).withTags(["wcag2a", "wcag2aa", "wcag21aa"]).analyze();
  expect(accessibility.violations).toEqual([]);
  await page.getByLabel(/I reviewed the actual information/).check();
  await page.getByRole("button", { name: "Confirm and submit intake" }).click();
  await expect(page.getByText(/Feasibility review is pending. No payment was started/)).toBeVisible();
});

test("uploaded compound facts can correct several fields together before full confirmation", async ({ page }) => {
  await page.goto("/get-started?source=compound");
  await page.getByRole("radio", { name: "Correct it" }).check();
  await page.getByLabel("Correct employer", { exact: true }).fill("Corrected Store");
  await page.getByLabel("Correct historical title", { exact: true }).fill("Team lead");
  await page.getByLabel("Correct dates", { exact: true }).fill("2021–2024");
  await page.getByLabel("Correct phone", { exact: true }).fill("555 0199");
  await page.getByLabel(/I checked for missing or outdated/).check();
  await page.getByRole("button", { name: /Save and continue/ }).click();
  await page.getByRole("checkbox", { name: "Remote" }).check();
  await page.getByLabel("U.S. state or District of Columbia required").selectOption("VA");
  await page.getByRole("checkbox", { name: "Full Time" }).check();
  await page.getByLabel(/I agree to/).check();
  await page.getByRole("button", { name: "Review my information" }).click();
  const review = page.getByRole("region", { name: "Document facts and corrections" });
  for (const value of ["Corrected Store", "Team lead", "2021–2024", "555 0199"]) await expect(review).toContainText(value);
  await expect(page.getByRole("button", { name: "Confirm and submit intake" })).toBeDisabled();
  await page.getByLabel(/I reviewed the actual information/).check();
  await page.getByRole("button", { name: "Confirm and submit intake" }).click();
  await expect(page.getByText(/Feasibility review is pending. No payment was started/)).toBeVisible();
});
