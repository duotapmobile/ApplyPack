export const launchMaintenance = { cronSchedule: "*/15 * * * *", maxAgeMinutes: "45" } as const;
export const launchLockNames = ["APP_CHECKOUT_ENABLED", "APP_CANARY_CHECKOUT_ENABLED", "APP_REHEARSAL_CHECKOUT_ENABLED",
  "APP_LIVE_PAYMENTS_ENABLED", "APP_JOB_BOARD_CHECKOUT_ENABLED", "APP_JOB_SOURCE_SYNC_ENABLED"] as const;

// Only these non-secret values may appear in configuration/rollback evidence.
export function launchConfigurationReceipt(values: Record<string, string | undefined>, expectedSha: string) {
  if (!/^[a-f0-9]{40}$/.test(expectedSha) || values.APP_EXPECTED_RELEASE_SHA !== expectedSha
    || !["staging", "production"].includes(values.APP_DEPLOYMENT_ENV || "")
    || values.APP_PAYMENT_MODE !== (values.APP_DEPLOYMENT_ENV === "production" ? "live" : "test")
    || values.APP_MANUAL_LAUNCH_SCOPE !== "MANUAL_ONLY"
    || values.APP_SEARCH_CAPACITY_PER_ROLLING_24H !== "1"
    || values.APP_APPLY_PACK_CAPACITY_PER_ROLLING_24H !== "2"
    || values.APP_MAINTENANCE_MAX_AGE_MINUTES !== launchMaintenance.maxAgeMinutes
    || launchLockNames.some((name) => values[name] !== "false")) {
    throw new Error("LAUNCH_LOCKED_CONFIGURATION_MISMATCH");
  }
  const publicValues = Object.fromEntries([...launchLockNames, "APP_EXPECTED_RELEASE_SHA", "APP_DEPLOYMENT_ENV",
    "APP_PAYMENT_MODE", "APP_MANUAL_LAUNCH_SCOPE", "APP_SEARCH_CAPACITY_PER_ROLLING_24H",
    "APP_APPLY_PACK_CAPACITY_PER_ROLLING_24H", "APP_MAINTENANCE_MAX_AGE_MINUTES"].sort().map((key) => [key, values[key]]));
  return { profile: values.APP_DEPLOYMENT_ENV === "production" ? ".railway/production.ts" : ".railway/launch.ts", webConfig: "railway.launch.web.json", maintenanceConfig: "railway.launch.maintenance.json",
    dockerfile: "Dockerfile.launch", checkSuites: true,
    cronSchedule: launchMaintenance.cronSchedule, values: publicValues,
    sha256: createHash("sha256").update(JSON.stringify(publicValues)).digest("hex") };
}
